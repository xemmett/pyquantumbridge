static const uint32_t cPaletteSize = 256;

// -------------------------------------------------------------------------------------------------------------------
const uint32_t GetPlatformSpecificColour(uint8_t Sample, uint8_t Red, uint8_t Green, uint8_t Blue)
{
	return (static_cast<uint32_t>(Sample) << 24u) + (static_cast<uint32_t>(Red) << 16u) + (static_cast<uint32_t>(Green) << 8u) + static_cast<uint32_t>(Blue);
}
